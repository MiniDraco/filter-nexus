"""Drop candidates already in filters.db; flag near matches for review. Run from filter-nexus/."""
import re, sqlite3, sys
sys.path.insert(0, "research")
from candidates import C

def norm(s): return re.sub(r"[^a-z0-9]", "", s.lower())
def base(s): return norm(re.sub(r"\(.*?\)|\[.*?\]", "", s))

db = sqlite3.connect("filters.db")
known = {}
for fid, name, eid, status in db.execute("SELECT id, name, engine_id, status FROM filter"):
    for k in {norm(name), base(name), norm(eid or "")} - {""}: known.setdefault(k, (name, status))
for fid, app, name in db.execute("SELECT filter_id, app, name FROM alias"):
    st = db.execute("SELECT name, status FROM filter WHERE id=?", (fid,)).fetchone()
    for k in {norm(name), base(name)} - {""}: known.setdefault(k, st)

seen, new, dup, near = set(), [], [], []
for n, src, cat, fe in C:
    k = norm(n)
    if k in seen: continue
    seen.add(k)
    hit = known.get(k) or known.get(base(n))
    if hit: dup.append((n, hit)); continue
    b = base(n)
    close = [v for kk, v in known.items() if len(b) >= 7 and len(kk) >= 7 and (b in kk or kk in b)]
    (near if close else new).append((n, src, cat, fe, close[:2]))
print(f"candidates {len(C)}  unique {len(seen)}  already-in-db {len(dup)}  new {len(new)}  near-match {len(near)}")
print("\n-- dropped (already present):"); [print("  ", n, "->", h) for n, h in dup]
print("\n-- near matches (review):"); [print("  ", n, "~", cl) for n, s, c, f, cl in near]

# ---- manual review of near matches: these ARE already covered (checked option lists 2026-10-17) ----
