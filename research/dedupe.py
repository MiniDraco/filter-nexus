           "Shades of Gray constancy", "White Patch (max-RGB) constancy", "Exponential tone mapping", "Shi-Tomasi", "Gold-Meinel sharpening",
           "Lottes 2016 (ext.)", "Polaroid SX-70", "Sumi-e ink wash", "Kodak Aerochrome infrared", "Neon glow edges", "Watercolor bleed",
